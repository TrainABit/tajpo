enum Keyboard {
    /// The virtual key code that types `character` while ⌘ is held in the
    /// current ASCII-capable layout. Fixes ⌘C/⌘V on Dvorak, Colemak, AZERTY…
    static func keyCode(for character: Character, fallback: CGKeyCode) -> CGKeyCode {
        guard let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
            return fallback
        }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue()
        guard let bytes = CFDataGetBytePtr(data) else { return fallback }
        let layout = UnsafeRawPointer(bytes).assumingMemoryBound(to: UCKeyboardLayout.self)
        let target = String(character).lowercased()
        let commandState = UInt32((cmdKey >> 8) & 0xFF)
        for code in 0..<128 {
            var deadKeyState: UInt32 = 0
            var characters = [UniChar](repeating: 0, count: 4)
            var length = 0
            let status = UCKeyTranslate(
                layout,
                UInt16(code),
                UInt16(kUCKeyActionDown),
                commandState,
                UInt32(LMGetKbdType()),
                OptionBits(1 << kUCKeyTranslateNoDeadKeysBit),
                &deadKeyState,
                characters.count,
                &length,
                &characters
            )
            if status == noErr, length > 0,
               String(utf16CodeUnits: characters, count: length).lowercased() == target {
                return CGKeyCode(code)
            }
        }
        return fallback
    }

    /// Waits (up to `timeout`) until no modifier keys are physically held, so a
    /// synthetic ⌘C isn't combined with the ⌃⌥ still held from the shortcut.
    static func waitForModifierRelease(timeout: Duration = .milliseconds(600)) async {
        let modifiers: CGEventFlags = [.maskCommand, .maskAlternate, .maskControl, .maskShift]
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline {
            if CGEventSource.flagsState(.combinedSessionState).intersection(modifiers).isEmpty { return }
            try? await Task.sleep(for: .milliseconds(15))
        }
    }

    static func postCommandShortcut(_ character: Character, fallback: CGKeyCode) {
        let key = keyCode(for: character, fallback: fallback)
        let source = CGEventSource(stateID: .privateState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

enum PasteboardMarker {
    // nspasteboard.org conventions, honored by clipboard managers.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}

/// A copy of the pasteboard's items with their types in original order.
/// Initialization fails closed if a promised/lazy representation cannot be
/// materialized; silently dropping a type could destroy a user's clipboard.
struct ClipboardSnapshot {
    private static let maximumItemBytes = 10 * 1024 * 1024
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init?(_ pasteboard: NSPasteboard) {
        var copied: [[(NSPasteboard.PasteboardType, Data)]] = []
        var totalBytes = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var pairs: [(NSPasteboard.PasteboardType, Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { return nil }
                totalBytes += data.count
                guard totalBytes <= Self.maximumItemBytes else { return nil }
                pairs.append((type, data))
            }
            copied.append(pairs)
        }
        items = copied
    }

    /// Restores the saved items, marked so clipboard managers don't record
    /// them a second time.
    @discardableResult
    func restore(to pasteboard: NSPasteboard) -> Bool {
        pasteboard.clearContents()
        var failed = false
        let objects = items.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs where !item.setData(data, forType: type) {
                failed = true
            }
            return item
        }
        objects.first?.setData(Data(), forType: PasteboardMarker.transient)
        return !failed && (objects.isEmpty || pasteboard.writeObjects(objects))
    }
}

extension NSPasteboard {
    /// Writes text that clipboard managers should ignore.
    func writeTransient(_ text: String) -> Bool {
        clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: PasteboardMarker.transient)
        item.setData(Data(), forType: PasteboardMarker.concealed)
        item.setData(Data(), forType: PasteboardMarker.autoGenerated)
        return writeObjects([item])
    }

    var deniesProgrammaticAccess: Bool {
        if #available(macOS 15.4, *) {
            return accessBehavior == .alwaysDeny
        }
        return false
    }
}
